// Катастрофа: свежая перетасованная копия списка (Фишер–Йетс), берём одну карту через pop().
// В одной игре катастрофа одна, поэтому повторов внутри игры быть не может; с seed — воспроизводимо.
function drawCatastrophe(seed = process.env.BUNKER_SEED) {
  const pile = shuffle(CATASTROPHES, makeRng(seed));
  if (!pile.length) console.warn('[deck] Список катастроф пуст.');
  return pile.pop();
}

