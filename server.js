const wordCount = s => s.trim().split(/\s+/).length;

// BASE, STATE, LIMIT + опциональный DETAIL; длина значения не больше 14 слов.
// Помимо русской строки возвращается «рецепт» (rec): из каких карточек она собрана. По нему клиент
// собирает ту же строку на любом языке (переводы карточек — content-i18n/<язык>.json).
const mix = (set, m) => {
  const baseRaw = set.base.draw();
  const base = m === undefined ? baseRaw : baseRaw.replace('{m}', m);
  const state = set.state.draw();
  const limit = set.limit.draw();
  let out = `${base}, ${state}, ${limit}`;
  let rec = [m === undefined ? { k: baseRaw } : { k: baseRaw, m }, ', ', { k: state }, ', ', { k: limit }];
  if (wordCount(out) > 14) { out = `${base}, ${state}`; rec = rec.slice(0, 3); }
  if (randomInt(0, 4) > 0) {
    const detail = set.detail.draw();
    if (wordCount(out) + wordCount(detail) <= 14) { out += `; ${detail}`; rec.push('; ', { k: detail }); }
  }
  return { text: out, rec };
};

const seatsWord = n => {
  const t = n % 10, h = n % 100;
  if (t === 1 && h !== 11) return 'место';
  if (t >= 2 && t <= 4 && (h < 12 || h > 14)) return 'места';
  return 'мест';
};

function genBunker(seats) {
  const seatsText = `${seats} ${seatsWord(seats)}`;
  const capBase = bunkerDeck.capBase.draw(), capLimit = bunkerDeck.capLimit.draw();
  const capacity = `${capBase.replace('{s}', seatsText)}, ${capLimit}`;
  const capRec = [{ k: capBase, s: seats }, ', ', { k: capLimit }];

  const months = randomInt(6, 41);
  const cond = bunkerDeck.autoCond.draw();
  const sep = /^(затем|если)/.test(cond) ? ', ' : ' ';
  let autonomy = `${months} мес.${sep}${cond}`;
  const autoRec = [{ mo: months }, sep, { k: cond }];
  if (randomInt(0, 2) === 1) {
    const lim = bunkerDeck.autoLimit.draw();
    if (wordCount(autonomy) + wordCount(lim) <= 14) { autonomy += `, ${lim}`; autoRec.push(', ', { k: lim }); }
  }

  const food = mix(bunkerDeck.food, randomInt(3, 26));
  const water = mix(bunkerDeck.water), power = mix(bunkerDeck.power), med = mix(bunkerDeck.med), vent = mix(bunkerDeck.vent);
  const room = bunkerDeck.rooms.draw();

  return {
    text: {
      'Вместимость': capacity, 'Еда': food.text, 'Вода': water.text, 'Электричество': power.text,
      'Медицина': med.text, 'Вентиляция': vent.text, 'Автономность': autonomy, 'Помещения': room
    },
    recipe: {
      'Вместимость': capRec, 'Еда': food.rec, 'Вода': water.rec, 'Электричество': power.rec,
      'Медицина': med.rec, 'Вентиляция': vent.rec, 'Автономность': autoRec, 'Помещения': [{ k: room }]
    }
  };
}


