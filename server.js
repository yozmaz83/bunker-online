const mkDeck = pool => ({ pool, pile: shuffle(pool), draw() { if (!this.pile.length) this.pile = shuffle(this.pool); return this.pile.pop(); } });
const mkSet = (base, state, limit, detail) => ({ base: mkDeck(base), state: mkDeck(state), limit: mkDeck(limit), detail: mkDeck(detail) });

