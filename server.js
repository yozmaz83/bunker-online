// ===== ПЕРЕМЕШИВАНИЕ (Фишер–Йетс) И РАЗДАЧА БЕЗ ПОВТОРОВ =====
// Seed: если задан (env BUNKER_SEED или аргумент seed) — порядок воспроизводим (mulberry32).
// Без seed используется криптостойкий randomInt Node.js — каждый раз новый случайный порядок.
function makeRng(seed) {
  if (seed === undefined || seed === null || seed === '') return n => randomInt(n);
  let h = 1779033703 ^ String(seed).length;
  for (const ch of String(seed)) { h = Math.imul(h ^ ch.charCodeAt(0), 3432918353); h = (h << 13) | (h >>> 19); }
  let a = h >>> 0;
  return n => {
    a = (a + 0x6D2B79F5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return Math.floor((((t ^ (t >>> 14)) >>> 0) / 4294967296) * n);
  };
}

// Фишер–Йетс: возвращает НОВЫЙ перемешанный массив, исходный не меняется.
function shuffle(arr, rng = makeRng()) {
  const a = arr.slice();
  for (let i = a.length - 1; i > 0; i--) {
    const j = rng(i + 1);
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

